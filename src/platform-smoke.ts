import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import JSZip from "jszip";

const originalCwd = process.cwd();
const temp = await fs.mkdtemp(path.join(os.tmpdir(), "content-platform-test-"));
try {
  await fs.symlink(path.join(originalCwd, "node_modules"), path.join(temp, "node_modules"), "dir");
  process.chdir(temp);
  const auth = await import("./lib/platform-auth");
  const platform = await import("./lib/platform");
  const database = await import("./lib/platform-db");
  const simple = await import("./lib/simple-content");
  const freeform = await import("./lib/freeform-design");
  const components = await import("./lib/semantic-component-image");
  const whatsapp = await import("./lib/whatsapp");

  const alice = auth.createUser("alice@example.com", "correct-horse-battery-staple");
  const bob = auth.createUser("bob@example.com", "another-long-secret-password");
  const companyA = platform.createCompany("Company A", alice);
  const companyB = platform.createCompany("Company B", bob);
  const onboardingCompany = platform.createOnboardingCompany("New Studio", alice, { description: "A design studio", website: "https://studio.example" });
  assert.equal(platform.getCompany(onboardingCompany)?.onboarding_step, 2);
  platform.saveOnboardingCompany(onboardingCompany, "New Studio", { ...platform.getBrand(onboardingCompany), audience: "Independent makers", socialLinks: [{ label: "Instagram", url: "https://instagram.com/studio" }] }, 5);
  assert.equal(platform.getCompany(onboardingCompany)?.onboarding_step, 5);
  const onboardingProject = platform.createProjectRecord({ companyId: onboardingCompany, creatorId: alice, contentType: "post", brief: "A studio update" });
  assert.equal(JSON.parse(database.projectRow(onboardingProject)!.brand_snapshot_json).audience, "Independent makers");
  assert.equal(auth.roleFor(alice, companyA), "owner");
  assert.equal(auth.roleFor(alice, companyB), null);
  database.db().prepare("UPDATE users SET is_root=1 WHERE id=?").run(alice);
  assert.equal(auth.roleFor(alice, companyB), "owner");
  assert.equal(platform.companiesForUser(alice).length, 3);
  database.db().prepare("UPDATE users SET is_root=0 WHERE id=?").run(alice);

  const projectId = platform.createProjectRecord({ companyId: companyA, creatorId: alice, contentType: "presentation", brief: "An editable deck" });
  assert.equal(platform.listCompanyProjects(companyB).length, 0);
  const result = await simple.saveSimpleArtifact(projectId, { type: "presentation", title: "Deck", slides: [{ title: "One", body: "Alpha" }, { title: "Two", body: "Beta" }, { title: "Three", body: "Gamma" }] });
  const artifact = JSON.parse(result.artifact_json!);
  const requestWorkspace = await import("./lib/request-workspace");
  const readySnapshot = await requestWorkspace.requestSnapshot(projectId);
  assert.equal(readySnapshot.output?.href, `/content/${projectId}`);
  assert.equal(readySnapshot.output?.canOpen, true);
  assert.deepEqual(readySnapshot.output?.pages, ["One", "Two", "Three"]);
  const zip = await JSZip.loadAsync(await fs.readFile(artifact.pptxPath));
  assert.ok(zip.file("ppt/slides/slide1.xml"));
  assert.ok((await zip.file("ppt/slides/slide1.xml")!.async("string")).includes("Alpha"));
  const carouselId = platform.createProjectRecord({ companyId: companyB, creatorId: bob, contentType: "carousel", brief: "A neutral company carousel" });
  const carousel = await simple.saveSimpleArtifact(carouselId, { type: "carousel", title: "Guide", caption: "Save this", slides: [{ title: "A", body: "One point" }, { title: "B", body: "Another point" }, { title: "C", body: "Third point" }] });
  const carouselArtifact = JSON.parse(carousel.artifact_json!);
  assert.equal(carouselArtifact.imagePaths.length, 3);
  const sharp = (await import("sharp")).default;
  assert.equal((await sharp(carouselArtifact.imagePaths[0]).metadata()).width, 1080);
  const storyId = platform.createProjectRecord({ companyId: companyA, creatorId: alice, contentType: "story", brief: "A short Instagram Story" });
  const story = await simple.saveSimpleArtifact(storyId, { type: "story", headline: "One useful idea", subline: "Keep it simple and clear.", cta: "Learn more" });
  const storyArtifact = JSON.parse(story.artifact_json!);
  const storyMetadata = await sharp(storyArtifact.imagePath).metadata();
  assert.equal(storyMetadata.width, 1080);
  assert.equal(storyMetadata.height, 1920);

  const designId = platform.createProjectRecord({ companyId: companyA, creatorId: alice, contentType: "design", brief: "Ceremonial cheque for a competition", status: "awaiting-input", artifact: { phase: "intake", instructions: "", referenceNotes: "", answers: [], sources: [], question: { text: "What size should the cheque be?", options: ["180 × 90 mm", "Custom"] } } });
  freeform.answerDesignQuestion(designId, "1");
  const designIntake = JSON.parse(database.projectRow(designId)!.artifact_json!);
  assert.equal(designIntake.answers[0].answer, "180 × 90 mm");
  const design = await freeform.saveDesignSpec(designId, { type: "design", title: "Competition award", size: { label: "Digital cheque preview", widthPx: 1800, heightPx: 900, note: "" }, background: "#F2EDFF", elements: [{ kind: "rect", x: 0.05, y: 0.1, width: 0.9, height: 0.8, fill: "#FFFFFF", strokeWidth: 0 }, { kind: "text", text: "Competition winner", x: 0.12, y: 0.35, width: 0.7, fontSize: 0.06, color: "#111111", weight: "bold", align: "left" }], sources: [] });
  const designArtifact = JSON.parse(design.artifact_json!);
  assert.equal((await sharp(designArtifact.imagePath).metadata()).width, 1800);
  assert.ok((await fs.readFile(designArtifact.svgPath, "utf8")).includes("Competition winner"));
  const picture = await sharp({ create: { width: 100, height: 80, channels: 4, background: "#ff0000" } }).png().toBuffer();
  const companyPictureId = await platform.storeCompanyAsset(companyA, "diagram.png", picture, "image/png", "artwork");
  assert.match(await components.componentIllustrationData(`company:${companyPictureId}`, companyA), /^data:image\/png;base64,/);
  await assert.rejects(components.componentIllustrationData(`company:${companyPictureId}`, companyB));
  const uploadedPath = platform.getCompanyAsset(companyA, companyPictureId)!.disk_path;
  platform.saveBrand(companyA, { ...platform.getBrand(companyA), artworkAssetIds: [companyPictureId], themeCard: { tagline: "A clear idea", personality: ["Useful"], typography: "Sans serif", imagery: "Illustrated", source: "Assets", generatedAt: new Date().toISOString(), featuredAssetId: companyPictureId } });
  await platform.deleteCompanyAsset(companyA, companyPictureId);
  assert.equal(platform.getCompanyAsset(companyA, companyPictureId), undefined);
  assert.equal(platform.getBrand(companyA).themeCard?.featuredAssetId, null);
  assert.deepEqual(platform.getBrand(companyA).artworkAssetIds, []);
  await assert.rejects(fs.access(uploadedPath));
  const pictureId = await platform.storeProjectReference(designId, "award.png", picture, "image/png");
  const editedDesign = await freeform.saveDesignSpec(designId, { ...designArtifact, elements: [...designArtifact.elements, { kind: "text", text: "Thank you", x: 0.2, y: 0.6, width: 0.5, fontSize: 0.04, color: "#111111", weight: "regular", italic: true, align: "left" }, { kind: "image", referenceId: pictureId, x: 0.7, y: 0.1, width: 0.2, height: 0.3, cropX: 0.2, cropY: 0.1, cropWidth: 0.5, cropHeight: 0.7 }] });
  const editedSvg = await fs.readFile(JSON.parse(editedDesign.artifact_json!).svgPath, "utf8");
  assert.ok(editedSvg.includes('font-style="italic"'));
  assert.ok(editedSvg.includes('href="data:image/png;base64,'));

  const invitation = auth.createInvitation(companyA, "bob@example.com", "member");
  assert.throws(() => auth.acceptInvitation(invitation, "bob@example.com", "wrong-password"));
  auth.acceptInvitation(invitation, "bob@example.com", "another-long-secret-password");
  assert.equal(auth.roleFor(bob, companyA), "member");
  const expiredInvite = auth.createInvitation(companyA, "new@example.com", "member");
  database.db().prepare("UPDATE invitations SET expires_at='2000-01-01T00:00:00.000Z' WHERE token_hash=?").run(database.hashToken(expiredInvite));
  assert.throws(() => auth.acceptInvitation(expiredInvite, "new@example.com", "another-long-password"));

  const link = platform.newShareToken(projectId);
  assert.equal(platform.projectForShareToken(link)?.id, projectId);
  database.db().prepare("UPDATE share_links SET expires_at='2000-01-01T00:00:00.000Z' WHERE token_hash=?").run(database.hashToken(link));
  assert.equal(platform.projectForShareToken(link), undefined);

  process.env.WHATSAPP_APP_SECRET = "test-secret";
  const raw = "{\"entry\":[]}";
  const crypto = await import("node:crypto");
  const signature = `sha256=${crypto.createHmac("sha256", "test-secret").update(raw).digest("hex")}`;
  assert.equal(whatsapp.verifyMetaSignature(raw, signature), true);
  assert.equal(whatsapp.verifyMetaSignature(raw + " ", signature), false);
  await whatsapp.processWhatsAppMessage({ phone: "123456789", externalId: "external-1", text: "hello" });
  await whatsapp.processWhatsAppMessage({ phone: "123456789", externalId: "external-1", text: "hello" });
  assert.equal((database.db().prepare("SELECT count(*) AS n FROM messages WHERE direction='in'").get() as { n: number }).n, 1);
  const code = whatsapp.createPairingCode(alice);
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "pair-1", text: code });
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "brief-1", text: "Make an Instagram Story about home learning" });
  assert.equal((database.db().prepare("SELECT count(*) AS n FROM projects").get() as { n: number }).n, 5);
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "company-1", text: "Company A" });
  const conversation = database.db().prepare("SELECT state_json FROM conversations WHERE phone=?").get("85212345678") as { state_json: string };
  const whatsappProjectId = JSON.parse(conversation.state_json).projectId as string;
  assert.equal(database.projectRow(whatsappProjectId)?.company_id, companyA);
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "company-1", text: "Company A" });
  assert.equal((database.db().prepare("SELECT count(*) AS n FROM projects").get() as { n: number }).n, 6);
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "cancel-1", text: "cancel" });
  assert.equal(database.projectRow(whatsappProjectId)?.status, "stopped");
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "story-brief", text: "Make an Instagram Story about a new study habit" });
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "story-company", text: "Company A" });
  const storyConversation = database.db().prepare("SELECT state_json FROM conversations WHERE phone=?").get("85212345678") as { state_json: string };
  assert.equal(database.projectRow(JSON.parse(storyConversation.state_json).projectId)?.content_type, "story");
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "design-reset", text: "cancel" });
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "design-brief", text: "Design a cheque for a competition" });
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "design-company", text: "Company A" });
  const designConversation = database.db().prepare("SELECT state_json FROM conversations WHERE phone=?").get("85212345678") as { state_json: string };
  assert.equal(JSON.parse(designConversation.state_json).projectId, undefined);

  const intake = await import("./lib/intake");
  const workflow = await import("./lib/workflow-state");
  const gates = await import("./lib/quality-gates");
  const revisions = await import("./lib/workflow-revision");
  const priorGateway = process.env.AI_GATEWAY_API_KEY;
  const priorOpenRouter = process.env.OPENROUTER_API_KEY;
  delete process.env.AI_GATEWAY_API_KEY;
  delete process.env.OPENROUTER_API_KEY;
  try {
    // Clarification is model-generated, not a hard-coded offline questionnaire.
    // The platform smoke test makes no provider calls; model interaction has its own tests.
    const unresolvedId = intake.createIntakeRequest(companyA, alice, "Create something about home learning");
    await assert.rejects(intake.advanceIntake(unresolvedId), /AI provider is required/);
    assert.equal(workflow.workflowState(unresolvedId)?.question, null);
    assert.deepEqual(workflow.workflowState(unresolvedId)?.answers, []);
    const intakeBrief = "Create an Instagram Story about home learning. Audience: families supporting home learning. Tone: friendly and practical.";
    const intakeId = intake.createIntakeRequest(companyA, alice, intakeBrief);
    await intake.advanceIntake(intakeId);
    assert.equal(database.projectRow(intakeId)?.content_type, "story");
    assert.equal(database.projectRow(intakeId)?.brief, intakeBrief);
    assert.equal(workflow.workflowState(intakeId)?.specialist, "story");
    assert.equal(workflow.workflowState(intakeId)?.question, null);
    assert.deepEqual(workflow.workflowState(intakeId)?.answers, []);
    assert.deepEqual(workflow.workflowEvents(intakeId).map((event) => event.kind), ["prompt", "request-created", "creative-context", "route"]);
    const comingSoonId = intake.createIntakeRequest(companyA, alice, "Write an article about revision techniques");
    await intake.advanceIntake(comingSoonId);
    assert.equal(database.projectRow(comingSoonId)?.status, "coming-soon");
    assert.equal(workflow.workflowState(comingSoonId)?.phase, "coming-soon");
    assert.equal((database.db().prepare("SELECT count(*) AS n FROM jobs WHERE project_id=? AND kind<>'intake-route'").get(comingSoonId) as { n: number }).n, 0);
    const validExport = await gates.reviewSimpleExport(simple.SimpleArtifactSchema.parse(artifact));
    assert.equal(validExport.passed, true);
    const invalidExport = await gates.reviewSimpleExport(simple.SimpleArtifactSchema.parse({ ...carouselArtifact, imagePaths: ["/does-not-exist.png"] }));
    assert.equal(invalidExport.passed, false);
    const versionBeforeRevision = database.projectRow(projectId)!.version;
    await revisions.queueWorkflowRevision(projectId, "Make the explanation clearer", null);
    assert.equal(database.projectRow(projectId)?.id, projectId);
    const snapshot = database.db().prepare("SELECT artifact_json FROM workflow_artifact_versions WHERE project_id=? AND version=?").get(projectId, versionBeforeRevision) as { artifact_json: string };
    assert.equal(JSON.parse(snapshot.artifact_json).title, "Deck");
    assert.equal(database.projectRow(projectId)?.status, "queued");
    await assert.rejects(revisions.queueWorkflowRevision(intakeId, "Make an article", "article"), /Coming Soon/);
  } finally {
    if (priorGateway === undefined) delete process.env.AI_GATEWAY_API_KEY; else process.env.AI_GATEWAY_API_KEY = priorGateway;
    if (priorOpenRouter === undefined) delete process.env.OPENROUTER_API_KEY; else process.env.OPENROUTER_API_KEY = priorOpenRouter;
  }
  // Poster follows the normal company snapshot, measured export and versioning path.
  const posterFont = await platform.storeCompanyAsset(companyA, "Manrope.woff2", await fs.readFile(path.join(originalCwd, "node_modules/@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2")), "font/woff2", "font");
  platform.saveBrand(companyA, { ...platform.getBrand(companyA), fontAssetIds: [posterFont] });
  const posterId = platform.createProjectRecord({ companyId: companyA, creatorId: alice, contentType: "poster", brief: "Create an A4 poster about one useful idea." });
  const poster = await simple.saveSimpleArtifact(posterId, { type: "poster", headline: "One useful idea.", subline: "Make it clear.", cta: "Start here.", designVersion: 2 });
  const posterArtifact = JSON.parse(poster.artifact_json!);
  const posterMeta = await sharp(posterArtifact.imagePath).metadata();
  assert.equal(posterMeta.width, 1240); assert.equal(posterMeta.height, 1754);
  assert.equal(posterArtifact.renderEvidence[0].fonts.some((font: string) => font.includes("Manrope.woff2")), true);
  assert.equal((await requestWorkspace.requestSnapshot(posterId)).output?.canOpen, true);
  const firstPosterBytes = await fs.readFile(posterArtifact.imagePath);
  const editedPoster = await simple.saveSimpleArtifact(posterId, { ...posterArtifact, headline: "A clearer idea." }, poster.version);
  assert.notEqual(JSON.parse(editedPoster.artifact_json!).imagePath, posterArtifact.imagePath);
  assert.deepEqual(await fs.readFile(posterArtifact.imagePath), firstPosterBytes);
  assert.equal((await gates.reviewSimpleExport(simple.SimpleArtifactSchema.parse(JSON.parse(editedPoster.artifact_json!)))).passed, true);
  await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "poster-brief", text: "Create a poster about shared learning" });
  let posterConversation = database.db().prepare("SELECT state_json FROM conversations WHERE phone=?").get("85212345678") as { state_json: string };
  if (!JSON.parse(posterConversation.state_json).projectId) {
    await whatsapp.processWhatsAppMessage({ phone: "85212345678", externalId: "poster-company", text: "Company A" });
    posterConversation = database.db().prepare("SELECT state_json FROM conversations WHERE phone=?").get("85212345678") as { state_json: string };
  }
  assert.equal(database.projectRow(JSON.parse(posterConversation.state_json).projectId)?.content_type, "poster");
  process.stdout.write("Platform smoke checks passed.\n");
} finally {
  process.chdir(originalCwd);
  await fs.rm(temp, { recursive: true, force: true });
}
