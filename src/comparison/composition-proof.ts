import fs from 'node:fs';
import path from 'node:path';
import { assertIsolation, LAB_DIR } from './config';
import { compositionBatchPath, type CompositionBatch } from './composition-report';
import { attemptDir, getAttempt, fingerprint } from './store';
import { getCompany, getBrand } from '../lib/platform';
import { projectRow } from '../lib/platform-db';
import { contentBrand } from '../lib/content-brand';
import { renderModernArtifact } from '../lib/modern-content';
import { SimpleArtifactSchema } from '../lib/simple-content';
import sharp from 'sharp';
assertIsolation();
const batch=JSON.parse(fs.readFileSync(compositionBatchPath(),'utf8')) as CompositionBatch;
const c=batch.cases.find(c=>c.format==='poster')!,a=getAttempt(c.attempts.at(-1)!);
if(a.status!=='needs-review')throw new Error('This proof is specifically for the reviewed poster weakness.');
const row=projectRow(a.projectId!)!;
const source=SimpleArtifactSchema.parse(JSON.parse(fs.readFileSync(path.join(attemptDir(a),'source.json'),'utf8')));
const brand=contentBrand(row.company_id,getCompany(row.company_id)!.name,JSON.parse(row.brand_snapshot_json) as ReturnType<typeof getBrand>,row.brief);
const dir=path.join(LAB_DIR,'composition-batch','proofs');
await renderModernArtifact(source,brand,dir);
if(source.type!=='poster'||!source.imagePath)throw new Error('Poster proof missing.');
const meta=await sharp(source.imagePath).metadata();
fs.writeFileSync(path.join(dir,'source.json'),JSON.stringify(source,null,2));
c.correction={file:source.imagePath,width:meta.width!,height:meta.height!,sourceAttemptId:a.id,fingerprint:fingerprint(),note:'A deterministic render of the same saved copy and composition with directional arrow connectors added. This is not a new model generation or a passed live QA result. The live attempt and its review remain unchanged.'};
fs.writeFileSync(compositionBatchPath(),JSON.stringify(batch,null,2));
console.log(JSON.stringify(c.correction));
